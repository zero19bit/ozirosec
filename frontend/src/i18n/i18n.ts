import i18n from 'i18next';
import { initReactI18next } from 'react-i18next';

export type Locale = 'en' | 'fa';

export const LOCALE_STORAGE_KEY = 'hackpath-locale';
export const DEFAULT_LOCALE: Locale = 'en';
export const SUPPORTED_LOCALES: Locale[] = ['en', 'fa'];

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && SUPPORTED_LOCALES.includes(value as Locale);
}

export function getInitialLocale(): Locale {
  if (typeof window === 'undefined') {
    return DEFAULT_LOCALE;
  }

  const directLocale = window.localStorage.getItem(LOCALE_STORAGE_KEY);
  if (isLocale(directLocale)) {
    return directLocale;
  }

  try {
    const persistedStore = window.localStorage.getItem('hackpath-store');
    const parsed = persistedStore ? JSON.parse(persistedStore) : null;
    const storeLocale = parsed?.state?.language;

    if (isLocale(storeLocale)) {
      return storeLocale;
    }
  } catch {
    return DEFAULT_LOCALE;
  }

  return DEFAULT_LOCALE;
}

export function getLocaleDirection(locale: Locale): 'ltr' | 'rtl' {
  return locale === 'fa' ? 'rtl' : 'ltr';
}

